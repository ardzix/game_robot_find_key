import assert from 'node:assert/strict';
import { mkdir, mkdtemp, copyFile, writeFile, readFile, readdir } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const results = path.join(root, 'test-results');
await mkdir(results, {recursive: true});
const fixture = await mkdtemp(path.join(results, 'checkpoint-fixture-'));
await mkdir(path.join(fixture, 'scripts'));
await copyFile(path.join(root, 'scripts', 'checkpoint.mjs'), path.join(fixture, 'scripts', 'checkpoint.mjs'));
await writeFile(path.join(fixture, 'original.txt'), 'baseline safe\n');
const run = (...args) => spawnSync(process.execPath, [path.join(fixture, 'scripts', 'checkpoint.mjs'), ...args], {cwd: fixture, encoding: 'utf8'});
assert.equal(run().status, 0);
assert.equal(run().status, 0);
const checkpoints = await readdir(path.join(fixture, 'checkpoints'));
assert.equal(checkpoints.length, 2, 'Timestamped checkpoints must not overwrite');
const first = path.join(fixture, 'checkpoints', checkpoints[0]);
await writeFile(path.join(fixture, 'original.txt'), 'later change\n');
const restored = path.join(results, path.basename(fixture) + '-restored');
assert.equal(run('--restore', first, '--to', restored).status, 0);
assert.equal(await readFile(path.join(restored, 'original.txt'), 'utf8'), 'baseline safe\n');
assert.notEqual(run('--restore', first, '--to', restored).status, 0, 'Restore must not overwrite existing destination');
await writeFile(path.join(first, 'snapshot', 'original.txt'), 'corrupted\n');
const failed = run('--restore', first, '--to', path.join(results, path.basename(fixture) + '-corrupt'));
assert.notEqual(failed.status, 0, 'Hash verification must reject corrupted checkpoint');
assert.match(failed.stderr, /Hash tidak cocok/);
console.log(JSON.stringify({ok: true, checks: ['unique checkpoints preserve earlier snapshot', 'restore reproduces original bytes after source modification', 'existing destination refused', 'corrupted file rejected by SHA-256'], fixture}, null, 2));
